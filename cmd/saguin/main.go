// heapFloor is a fixed minimum-heap allowance: memory the collector counts
// as live, so that it lets a small heap grow by at least that much garbage
// before collecting again (saguin). Go collects once the heap has grown by
// GOGC percent of what was live at the last collection, goroutine stacks and
// globals included. A broker holding few connections has a small live heap,
// so it collected often: at 200 connections and 10,000 QoS 1 messages a
// second the live heap was 2 MB, and the collector ran 46 times a second and
// took a fifth of the broker's CPU. Every collection also halves the stacks
// of readers parked between packets, which grow back on the next one. With
// 8 MB it ran 7 times a second and a message cost 19% less CPU; at 1,000
// connections, 9% less. At 10,000 the live heap is large enough that the
// floor changes little. 8 MB is the knee of a sweep of 0 to 32: 4 got half
// to two thirds of the gain, 16 and 32 little more than 8.
//
// **What it costs**: about 1 MB resident at rest, none of it the floor's own
// pages, and up to 10 MB under load, the extra garbage a later collection
// lets build up. It holds no pointers, so the collector never scans it, and
// nothing writes it, so the kernel never backs its pages
// (TestTheHeapFloorIsLivePointerFreeAndUntouched).
//
// **The Go runtime's own memory figures count it**, though the process's
// resident memory does not: runtime/metrics, runtime.MemStats and a heap
// profile show it as live, allocated by this package's init. It counts toward
// an operator's GOMEMLIMIT, so under a tight limit collection comes sooner,
// not later. GOMEMLIMIT only caps the collector's target and is no way to
// raise it; the alternatives are a higher GOGC, whose cost grows with the
// whole live heap, or GOGC=off with a GOMEMLIMIT (RFC 0005, "The runtime's
// own pauses, and the two variables that move them").
var heapFloor = withoutHugePages(make([]byte, heapFloorSize))

// heapFloorSize is heapFloor's size.
const heapFloorSize = 8 << 20

